function makeSamples() {
  const samples = [];
  let index = 0;

  while (samples.length < TARGET_SAMPLES) {
    for (const intent of intents) {
      for (const question of intent.questions) {
        for (const answer of intent.answers) {
          for (const style of styles) {
            for (const context of contexts) {
              const q = escapeLine(makeQuestion(intent, question, style, context, index));
              const a = escapeLine(makeAnswer(intent, answer, style, context, index));
              samples.push(`<s> 질문: ${q} 답변: ${a} </s>`);
              index += 1;

              if (samples.length >= TARGET_SAMPLES) {
                return samples;
              }
            }
          }
        }
      }
    }
  }

  return samples;
}

function writeLines(fileName, lines) {
  fs.mkdirSync(OUTPUT_DIR, { recursive: true });
  fs.writeFileSync(path.join(OUTPUT_DIR, fileName), `${lines.join("\n")}\n`, "utf8");
}

function buildDataset() {
  const samples = makeSamples();
  const validEvery = Math.floor(1 / VALID_RATIO);
  const valid = samples.filter((_, index) => index % validEvery === 0);
  const validSet = new Set(valid);
  const train = samples.filter((sample) => !validSet.has(sample));

  writeLines("train_001.txt", train);
  writeLines("valid_001.txt", valid);

  console.log(`samples=${samples.length}`);
  console.log(`train=${train.length}`);
  console.log(`valid=${valid.length}`);
  console.log(`output=${OUTPUT_DIR}`);
}

