function escapeLine(text) {
  return text.replace(/[<>]/g, "").replace(/\s+/g, " ").trim();
}

function makeQuestion(intent, q, style, context, index) {
  const followups = followupsByTopic[intent.topic] || [""];
  const suffix = followups[index % followups.length];
  const askStyle = intent.topic === "일상 인사" ? "" : style.ask;
  if (index % 4 === 0) {
    return `${context} ${askStyle}${q}${suffix}`.trim();
  }
  if (index % 4 === 1) {
    return `${askStyle}${q}${suffix}`.trim();
  }
  if (index % 4 === 2) {
    return intent.topic === "일상 인사"
      ? `${q}${suffix}`.trim()
      : `${intent.topic} 관련해서 ${q}${suffix}`.trim();
  }
  return intent.topic === "일상 인사"
    ? `${context} ${q}${suffix}`.trim()
    : `${context} ${q} ${style.ask}답해줘.${suffix}`.trim();
}

