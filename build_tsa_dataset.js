function cleanField(text) {
  return text.replace(/\t/g, " ").replace(/\r?\n/g, " ").replace(/\s+/g, " ").trim();
}

function hasFinalConsonant(text) {
  const last = [...text].reverse().find((char) => /[가-힣A-Za-z0-9]/.test(char));
  if (!last) {
    return false;
  }
  const code = last.charCodeAt(0);
  if (code >= 0xac00 && code <= 0xd7a3) {
    return (code - 0xac00) % 28 !== 0;
  }
  return /\d/.test(last);
}

function withJosa(topic, consonantJosa, vowelJosa) {
  return `${topic}${hasFinalConsonant(topic) ? consonantJosa : vowelJosa}`;
}

function render(pattern, topic, base, example) {
  return pattern
    .replaceAll("{topic_subject}", withJosa(topic, "은", "는"))
    .replaceAll("{topic_ga}", withJosa(topic, "이", "가"))
    .replaceAll("{topic_object}", withJosa(topic, "을", "를"))
    .replaceAll("{topic}", topic)
    .replaceAll("{base}", base)
    .replaceAll("{example}", example);
}

function buildSamples() {
  const samples = [];
  const seen = new Set();

  for (const [topic, base, example] of concepts) {
    for (const questionPattern of questionPatterns) {
      for (const answerPattern of answerPatterns) {
        const question = cleanField(render(questionPattern, topic, base, example));
        const answer = cleanField(render(answerPattern, topic, base, example));
        const line = `${question}\t${answer}`;
        if (!seen.has(line)) {
          seen.add(line);
          samples.push(line);
        }
        if (samples.length >= TARGET_SAMPLES) {
          return samples;
        }
      }
    }
  }

  return samples;
}

function deterministicShuffle(items) {
  const shuffled = [...items];
  let seed = 20260518;
  function nextRandom() {
    seed = (seed * 1664525 + 1013904223) >>> 0;
    return seed / 0x100000000;
  }

  for (let i = shuffled.length - 1; i > 0; i -= 1) {
    const j = Math.floor(nextRandom() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }
  return shuffled;
}

function writeShards(outputDir, prefix, samples) {
  fs.mkdirSync(outputDir, { recursive: true });
  for (const file of fs.readdirSync(outputDir)) {
    if (new RegExp(`^${prefix}_\\d{3}\\.txt$`).test(file)) {
      fs.unlinkSync(path.join(outputDir, file));
    }
  }
  fs.writeFileSync(path.join(outputDir, `${prefix}_001.txt`), `${samples.join("\n")}\n`, "utf8");
}

function buildDataset() {
  const samples = deterministicShuffle(buildSamples());
  if (samples.length < TARGET_SAMPLES) {
    throw new Error(`Only generated ${samples.length} samples.`);
  }

  const validEvery = Math.max(1, Math.floor(1 / VALID_RATIO));
  const valid = samples.filter((_, index) => index % validEvery === 0);
  const validSet = new Set(valid);
  const train = samples.filter((sample) => !validSet.has(sample));

  writeShards(TRAIN_DIR, "train", train);
  writeShards(VALID_DIR, "valid", valid);

  console.log(`samples=${samples.length}`);
  console.log(`unique=${new Set(samples).size}`);
  console.log(`train=${train.length}`);
  console.log(`valid=${valid.length}`);
  console.log(`train_output=${TRAIN_DIR}`);
  console.log(`valid_output=${VALID_DIR}`);
}

buildDataset();
